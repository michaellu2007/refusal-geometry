def entry(key, title, authors, year, eid, note):
    lines = [f"@misc{{{key},", f"  title = {{{title}}},", f"  author = {{{authors}}},"]
    if year:
        lines.append(f"  year = {{{year}}},")
    if eid:
        lines += [f"  eprint = {{{eid}}},", "  archivePrefix = {arXiv},",
                  f"  url = {{https://arxiv.org/abs/{eid}}},"]
    if note:
        lines.append(f"  note = {{{note}}},")
    lines.append("}")
    return "\n".join(lines)


